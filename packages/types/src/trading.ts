export const StrategySchema = z.object({
  id: z.string().uuid(),
  userId: z.string(),
  name: z.string().min(1).max(80),
  description: z.string().nullable(),
  instrumentFilter: z.array(InstrumentType).default([]),
  sessionFilter: z.array(TradingSession).default([]),
  timeframe: z.string().max(16).nullable(),
  rrTarget: z.number().positive().nullable(),
  entryRules: z.array(z.string()).default([]),
  exitRules: z.array(z.string()).default([]),
  isActive: z.boolean().default(true),
  createdAt: z.coerce.date(),
});
export type Strategy = z.infer<typeof StrategySchema>;
